"""Run every evaluation and write docs/evaluation_report.md (PLAN.md Phase 11).

Usage:  python -m ml.evaluation.run_all [--no-llm]      (or: python manage.py eval --local)

The agent is evaluated in rule-based mode always, and with the LLM too when OPENAI_API_KEY is set
(costs a few cents with gpt-4.1-mini). Results also go to model_metrics (split=eval) and MLflow.
"""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from sqlalchemy import insert  # noqa: E402

from app.core.config import get_settings  # noqa: E402
from app.db.models import ModelMetric  # noqa: E402
from app.db.session import get_sessionmaker  # noqa: E402
from ml.evaluation import run_agent_eval, run_forecast_eval, run_rag_eval, run_reco_eval  # noqa: E402

REPORT = ROOT / "docs" / "evaluation_report.md"


def pct(x: float | None) -> str:
    return "—" if x is None else f"{x * 100:.1f}%"


def f3(x: float | None) -> str:
    return "—" if x is None else f"{x:.3f}"


def agent_eval(db, mode: str) -> dict:  # noqa: ANN001
    key = os.environ.get("OPENAI_API_KEY")
    if mode == "fallback":
        os.environ["OPENAI_API_KEY"] = ""
    get_settings.cache_clear()
    try:
        return run_agent_eval.run(db, mode)
    finally:
        if key is not None:
            os.environ["OPENAI_API_KEY"] = key
        else:
            os.environ.pop("OPENAI_API_KEY", None)
        get_settings.cache_clear()


def render(reco: dict, fc: dict, agents: list[dict], rag: dict) -> str:
    L: list[str] = [
        "# Evaluation report",
        "",
        f"_Generated by `python manage.py eval` on {time.strftime('%Y-%m-%d %H:%M')}. Do not edit by hand._",
        "",
        "## 1. Recommendation quality",
        "",
    ]
    if reco["placeholder_labels"]:
        L += [
            f"> **Warning:** {reco['placeholder_labels']} of {reco['n_queries']} gold queries use PLACEHOLDER labels "
            "written by the developer, not independent expert judgement. These numbers only prove the pipeline "
            "works; they are not evidence of recommendation quality. Replace the labels in "
            "`tests/eval/reco_gold.yaml` (≥ 30 expert-labelled queries) before drawing conclusions.",
            "",
        ]
    keys = ["p@3", "p@5", "r@3", "r@5", "ndcg@3", "ndcg@5", "mrr"]
    L += ["| Ranking | " + " | ".join(k.upper() for k in keys) + " |", "|---" * (len(keys) + 1) + "|"]
    for name, m in (
        ("Business Opportunity Score", reco["system"]),
        ("Population only (baseline)", reco["population_only"]),
        ("Random (baseline)", reco["random"]),
    ):
        L.append(f"| {name} | " + " | ".join(f3(m.get(k)) for k in keys) + " |")
    L += ["", "**Ablation** — change in NDCG@5 when one factor's weight is set to 0 (negative = the factor helps):", ""]
    L += ["| Factor | ΔNDCG@5 |", "|---|---|"] + [
        f"| {k} | {v:+.3f} |" for k, v in reco["ablation_delta_ndcg5"].items()
    ]
    L += [
        "",
        "## 2. Forecast quality (rolling-origin backtest)",
        "",
        f"Run `{fc['run_id']}`. Selected model per target in bold.",
        "",
    ]
    L += ["| Indicator | Level | Model | sMAPE h1 | sMAPE h2 | MAE h1 | vs naive h1 |", "|---|---|---|---|---|---|---|"]
    for r in fc["rows"]:
        name = f"**{r['model']}**" if r["selected"] else r["model"]
        imp = r.get("improvement_vs_naive_pct_h1")
        L.append(
            f"| {r['indicator']} | {r['level']} | {name} | {r.get('smape_h1') or 0:.2f}% | "
            + (f"{r['smape_h2']:.2f}%" if r.get("smape_h2") is not None else "—")
            + f" | {r.get('mae_h1') or 0:,.0f} | "
            + (f"{imp:+.1f}%" if imp is not None else "—")
            + " |"
        )
    L += [
        "",
        "sMAPE = symmetric mean absolute percentage error; *vs naive* = % reduction of sMAPE against `naive_last` "
        "(positive = better). Services series start in 2020, so only naive / linear / Holt models are allowed there "
        "and Holt needs ≥ 5 points (it is excluded from selection when it was backtested on too few origins).",
        "",
        "## 3. Agent quality",
        "",
        "| Mode | Cases | Tool selection | Language | Insufficient-data detection | Numeric faithfulness | Task success | p50 latency | p95 latency | Tokens | Cost |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for a in agents:
        L.append(
            f"| {a['mode']} | {a['n_cases']} | {pct(a['tool_selection_accuracy'])} | {pct(a['language_accuracy'])} | "
            f"{pct(a['insufficient_detection_accuracy'])} | {pct(a['numeric_faithfulness'])} | {pct(a['task_success'])} | "
            f"{a['latency_p50_s']:.1f} s | {a['latency_p95_s']:.1f} s | {a['tokens_total']:,} | ${a['cost_usd_total']:.4f} |"
        )
    for a in agents:
        failed = [c for c in a["cases"] if not c["success"]]
        if failed:
            L += ["", f"Failed cases ({a['mode']}):", ""]
            for c in failed:
                why = [k for k in ("tool_ok", "lang_ok", "insufficient_ok", "faithful") if not c[k]]
                L.append(
                    f"- `{c['id']}` — tools {c['tools']}; failed: {', '.join(why) or c['error']}"
                    + (f"; unverified numbers {c['unsupported']}" if c["unsupported"] else "")
                )
    L += [
        "",
        "## 4. RAG",
        "",
        f"Retrieval mode: **{rag['mode']}** · {rag['n_questions']} questions · hit@5 **{pct(rag['hit@5'])}** · "
        f"MRR {rag['mrr']:.3f} · citation presence {pct(rag['citation_presence'])}",
        "",
        "| Question | Expected | Top 3 retrieved | Hit |",
        "|---|---|---|---|",
    ]
    for q in rag["questions"]:
        L.append(f"| {q['q']} | {', '.join(q['expect'])} | {', '.join(q['top'])} | {'✓' if q['hit'] else '✕'} |")
    L += [
        "",
        "## Notes",
        "",
        "- Gold labels for recommendations must come from independent judgement (local knowledge, market "
        "observation, expert interviews), never from the scoring features — otherwise the evaluation is circular.",
        "- Agent cases describe required behaviour (tools, language, refusal); they are in `tests/eval/agent_cases.yaml`.",
        "- All metrics are also stored in the `model_metrics` table (`split = 'eval'`) and logged to MLflow when available.",
        "",
    ]
    return "\n".join(L)


def store(db, run_id: str, reco: dict, agents: list[dict], rag: dict) -> None:  # noqa: ANN001
    rows = [
        {"run_id": run_id, "kind": "reco", "split": "eval", "model": name, "metric": k, "value": v}
        for name, m in (
            ("bos", reco["system"]),
            ("population_only", reco["population_only"]),
            ("random", reco["random"]),
        )
        for k, v in m.items()
    ]
    for a in agents:
        for k in (
            "tool_selection_accuracy",
            "language_accuracy",
            "insufficient_detection_accuracy",
            "numeric_faithfulness",
            "task_success",
            "latency_p95_s",
        ):
            rows.append(
                {"run_id": run_id, "kind": "agent", "split": "eval", "model": a["mode"], "metric": k, "value": a[k]}
            )
    for k in ("hit@5", "mrr", "citation_presence"):
        rows.append(
            {"run_id": run_id, "kind": "rag", "split": "eval", "model": rag["mode"], "metric": k, "value": rag[k]}
        )
    db.execute(insert(ModelMetric), rows)
    db.commit()


def log_mlflow(run_id: str, reco: dict, agents: list[dict], rag: dict) -> str:
    try:
        import mlflow

        from ml.forecasting.train import LOCAL_MLFLOW_URI

        uri = get_settings().mlflow_tracking_uri
        if uri.startswith("http"):
            import requests

            try:
                requests.get(uri.rstrip("/") + "/health", timeout=2).raise_for_status()
            except requests.RequestException:
                uri = LOCAL_MLFLOW_URI
        mlflow.set_tracking_uri(uri)
        mlflow.set_experiment("evaluation")
        with mlflow.start_run(run_name=f"eval-{run_id}"):
            mlflow.log_metrics({f"reco_{k.replace('@', '_at_')}": v for k, v in reco["system"].items()})
            for a in agents:
                mlflow.log_metric(f"agent_{a['mode']}_task_success", a["task_success"])
                mlflow.log_metric(f"agent_{a['mode']}_tool_accuracy", a["tool_selection_accuracy"])
            mlflow.log_metric("rag_hit_at_5", rag["hit@5"])
        return f"logged to MLflow ({uri})"
    except Exception as e:  # optional
        return f"MLflow skipped ({type(e).__name__})"


def main() -> None:
    use_llm = "--no-llm" not in sys.argv and bool(get_settings().openai_api_key)
    run_id = time.strftime("%Y%m%d%H%M%S")
    with get_sessionmaker()() as db:
        print("recommendations…")
        reco = run_reco_eval.run(db)
        print("forecasts…")
        fc = run_forecast_eval.run(db)
        print("agent (rule-based)…")
        agents = [agent_eval(db, "fallback")]
        if use_llm:
            print("agent (LLM)…")
            agents.append(agent_eval(db, "llm"))
        print("RAG…")
        rag = run_rag_eval.run(db)
        store(db, run_id, reco, agents, rag)
    REPORT.write_text(render(reco, fc, agents, rag), encoding="utf-8")
    print(f"\nreport: {REPORT.relative_to(ROOT)} · {log_mlflow(run_id, reco, agents, rag)}")
    s = reco["system"]
    print(
        f"reco  NDCG@5 {s['ndcg@5']:.3f} (population-only {reco['population_only']['ndcg@5']:.3f}, random {reco['random']['ndcg@5']:.3f})"
        + (f"  [{reco['placeholder_labels']} placeholder-labelled queries]" if reco["placeholder_labels"] else "")
    )
    for a in agents:
        print(
            f"agent {a['mode']:8} tools {pct(a['tool_selection_accuracy'])} · success {pct(a['task_success'])} · faithful {pct(a['numeric_faithfulness'])}"
        )
    print(f"rag   hit@5 {pct(rag['hit@5'])} ({rag['mode']})")


if __name__ == "__main__":
    main()
